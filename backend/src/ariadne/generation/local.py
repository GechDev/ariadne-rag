"""Local LLM provider backed by a Hugging Face transformers pipeline.

The pipeline is imported lazily so a cold start without ``transformers`` still
lets the rest of the application load. Use ``pip install ariadne[llm]`` to
enable this provider. Streaming is emulated by flushing tokens as they are
generated by the underlying model.
"""

from __future__ import annotations

from collections.abc import Iterator
from typing import Any

from ariadne.core.errors import LLMProviderError
from ariadne.generation.base import LLMProvider
from ariadne.logging import get_logger

logger = get_logger("generation.local")


class LocalLLMProvider(LLMProvider):
    """Text generation pipeline running on the local machine."""

    def __init__(
        self, model_name: str, *, max_new_tokens: int = 512, temperature: float = 0.2
    ) -> None:
        self.model_name = model_name
        self.max_new_tokens = max_new_tokens
        self.temperature = temperature
        self._pipeline: Any | None = None

    def _load(self) -> Any:
        if self._pipeline is None:
            try:
                from transformers import pipeline  # type: ignore[import-not-found]
            except ImportError as exc:
                raise LLMProviderError(
                    "transformers is not installed; add the 'llm' extra",
                    detail={"model": self.model_name},
                ) from exc
            logger.info("loading language model", extra={"model": self.model_name})
            self._pipeline = pipeline(
                "text-generation",
                model=self.model_name,
                max_new_tokens=self.max_new_tokens,
                temperature=self.temperature,
            )
        return self._pipeline

    def generate(self, prompt: str) -> str:
        pipe = self._load()
        try:
            result = pipe(prompt)
        except Exception as exc:
            logger.error("local generation failed", extra={"error": str(exc)})
            raise LLMProviderError(f"generation failed: {exc}") from exc
        return str(result[0]["generated_text"])

    def stream(self, prompt: str) -> Iterator[str]:
        answer = self.generate(prompt)
        for word in answer.split():
            yield word + " "
